const CONFIG_scale = 10;

function dist(p1, p2) { return Math.sqrt((p2.x - p1.x)**2 + (p2.y - p1.y)**2); }

function getMiterPolygon(seg, segments) {
    const t = seg.thickness;
    const halfT = t / 2;

    const dx = seg.end.x - seg.start.x;
    const dy = seg.end.y - seg.start.y;
    const len = Math.hypot(dx, dy);
    if (len < 0.001) return null;

    const dir = { x: dx / len, y: dy / len };
    const norm = { x: -dir.y, y: dir.x };

    let p1 = { x: seg.start.x + norm.x * halfT, y: seg.start.y + norm.y * halfT };
    let p2 = { x: seg.start.x - norm.x * halfT, y: seg.start.y - norm.y * halfT };
    let p3 = { x: seg.end.x - norm.x * halfT, y: seg.end.y - norm.y * halfT };
    let p4 = { x: seg.end.x + norm.x * halfT, y: seg.end.y + norm.y * halfT };

    function getIntersections(pt, isStart) {
        const conns = segments.filter(s => s !== seg && (dist(s.start, pt) < 0.1 || dist(s.end, pt) < 0.1));
        if (conns.length === 1) {
            const other = conns[0];
            const otherHalfT = other.thickness / 2;
            const odx = other.end.x - other.start.x;
            const ody = other.end.y - other.start.y;
            const olen = Math.hypot(odx, ody);
            let odir = { x: odx / olen, y: ody / olen };
            
            const sharedAtStart = dist(other.start, pt) < 0.1;
            if (!sharedAtStart) {
                odir = { x: -odir.x, y: -odir.y };
            }
            
            const onorm = { x: -odir.y, y: odir.x };
            const myDir = isStart ? { x: -dir.x, y: -dir.y } : { x: dir.x, y: dir.y }; 
            const myNorm = { x: -myDir.y, y: myDir.x };
            const cross = myDir.x * odir.y - myDir.y * odir.x;
            
            if (Math.abs(cross) > 0.01) {
                const intersect = (o1, d1, o2, d2) => {
                    const crossP = d1.x * d2.y - d1.y * d2.x;
                    if (Math.abs(crossP) < 1e-6) return o1;
                    const t = ((o2.x - o1.x) * d2.y - (o2.y - o1.y) * d2.x) / crossP;
                    return { x: o1.x + d1.x * t, y: o1.y + d1.y * t };
                };
                const myL = { x: pt.x + myNorm.x * halfT, y: pt.y + myNorm.y * halfT };
                const myR = { x: pt.x - myNorm.x * halfT, y: pt.y - myNorm.y * halfT };
                const otherL = { x: pt.x + onorm.x * otherHalfT, y: pt.y + onorm.y * otherHalfT };
                const otherR = { x: pt.x - onorm.x * otherHalfT, y: pt.y - onorm.y * otherHalfT };
                
                let i1 = intersect(myL, myDir, otherL, odir);
                let i2 = intersect(myL, myDir, otherR, odir);
                let iP1 = dist(i1, pt) < dist(i2, pt) ? i1 : i2;
                
                let i3 = intersect(myR, myDir, otherL, odir);
                let i4 = intersect(myR, myDir, otherR, odir);
                let iP2 = dist(i3, pt) < dist(i4, pt) ? i3 : i4;
                
                if (dist(iP1, pt) > halfT * 4) iP1 = myL;
                if (dist(iP2, pt) > halfT * 4) iP2 = myR;
                return isStart ? { left: iP2, right: iP1 } : { left: iP1, right: iP2 };
            }
        }
        return isStart ? { left: p1, right: p2 } : { left: p4, right: p3 };
    }

    const startPts = getIntersections(seg.start, true);
    const endPts = getIntersections(seg.end, false);
    return [startPts.left, startPts.right, endPts.right, endPts.left];
}

