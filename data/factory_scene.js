window.setMapMode = function(isMap) {
    if (!window.factoryGroups) return;
    
    // Прячем HTML-выноски при переходе в режим карты
    const labelsContainer = document.getElementById('labels-container');
    if (labelsContainer) {
        labelsContainer.style.opacity = isMap ? '0' : '1';
        labelsContainer.style.pointerEvents = isMap ? 'none' : 'auto';
        // Контейнер всегда должен пропускать клики (none), чтобы работало управление камерой
        labelsContainer.style.pointerEvents = 'none';
    }

    window.factoryGroups.zoneMarkers.forEach(m => {
        m.visible = !isMap && !m.userData.filteredOut;
    });

    if (!isMap) window.clearRoute();
};

window.buildGraph = function() {
    const graph = {};
    const tolerance = 5; // Погрешность соединения узлов
    
    function getNodeId(pt) {
        for (const id in graph) {
            if (dist(graph[id], pt) < tolerance) return id;
        }
        const newId = 'n_' + Object.keys(graph).length;
        graph[newId] = { x: pt.x, y: pt.y, edges: [] };
        return newId;
    }

    factoryData.walkways.forEach(w => {
        const id1 = getNodeId(w.start);
        const id2 = getNodeId(w.end);
        const d = dist(w.start, w.end);
        graph[id1].edges.push({ to: id2, weight: d });
        graph[id2].edges.push({ to: id1, weight: d });
    });
    return graph;
};

window.showRoute = function(startZoneId, endZoneId) {
    window.clearRoute();
    const startZone = factoryData.zones.find(z => z.id === startZoneId);
    const endZone = factoryData.zones.find(z => z.id === endZoneId);
    if (!startZone || !endZone) return;

    const graph = window.buildGraph();
    
    // Функция для поиска ближайшего перекрестка путей от центра зоны
    function getClosestNode(zone) {
        const zx = (zone.start.x + zone.end.x) / 2;
        const zy = (zone.start.y + zone.end.y) / 2;
        let minDist = Infinity;
        let closest = null;
        for (const id in graph) {
            const d = dist({x: zx, y: zy}, graph[id]);
            if (d < minDist) { minDist = d; closest = id; }
        }
        return closest;
    }

    const startNodeId = getClosestNode(startZone);
    const endNodeId = getClosestNode(endZone);

    if (!startNodeId || !endNodeId) {
        alert("Не удалось найти пешие пути рядом с выбранными зонами.");
        return;
    }

    // Алгоритм Дейкстры (поиск кратчайшего пути)
    const distances = {};
    const prev = {};
    const queue = new Set(Object.keys(graph));

    for (const id in graph) distances[id] = Infinity;
    distances[startNodeId] = 0;

    while (queue.size > 0) {
        let minId = null;
        for (const id of queue) {
            if (minId === null || distances[id] < distances[minId]) minId = id;
        }
        if (distances[minId] === Infinity || minId === endNodeId) break;
        queue.delete(minId);

        for (const edge of graph[minId].edges) {
            if (!queue.has(edge.to)) continue;
            const alt = distances[minId] + edge.weight;
            if (alt < distances[edge.to]) {
                distances[edge.to] = alt;
                prev[edge.to] = minId;
            }
        }
    }

    const pathIds = [];
    let curr = endNodeId;
    if (prev[curr] || curr === startNodeId) {
        while (curr) { pathIds.unshift(curr); curr = prev[curr]; }
    }

    if (pathIds.length < 2) {
        alert("Маршрут не найден. Пути не связаны между собой.");
        return;
    }

    // Отрисовка маршрута 3D линией
    for (let i = 0; i < pathIds.length - 1; i++) {
        const n1 = graph[pathIds[i]];
        const n2 = graph[pathIds[i+1]];
        const d = dist(n1, n2);
        const angle = Math.atan2(n2.y - n1.y, n2.x - n1.x);
        
        const geo = new THREE.BoxGeometry(d + 10, 8, 30);
        const mat = new THREE.MeshBasicMaterial({ color: 0x3355CC }); 
        const mesh = new THREE.Mesh(geo, mat);
        mesh.position.set((n1.x + n2.x)/2, 8, (n1.y + n2.y)/2);
        mesh.rotation.y = -angle;
        window.factoryGroups.route.add(mesh);
    }
};

window.clearRoute = function() {
    if (!window.factoryGroups || !window.factoryGroups.route) return;
    while(window.factoryGroups.route.children.length > 0) { 
        const child = window.factoryGroups.route.children[0];
        window.factoryGroups.route.remove(child); 
    }
};