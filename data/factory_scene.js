            const extrudeSettings = { depth: finalWallHeight3D, bevelEnabled: false };
            const geometry = new THREE.ExtrudeGeometry(shape, extrudeSettings);
            geometry.rotateX(Math.PI / 2);
            geometry.translate(0, finalWallHeight3D, 0);

